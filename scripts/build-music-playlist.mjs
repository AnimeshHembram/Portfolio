// Rebuilds Frontend/js/background-playlist.js from the audio files in
// Frontend/assets/music/background/. No dependencies.
//
//   node scripts/build-music-playlist.mjs
//
// - Keeps browser-playable audio only (.mp3 .m4a .aac .ogg .oga .opus .wav);
//   anything else (video, temp/partial downloads) is listed and skipped.
// - Title = file name without extension, with a trailing "[id]" removed.
// - Optional Frontend/assets/music/background/credits.json:
//     { "my-track.mp3": { "title": "...", "artist": "...", "credit": "...", "creditUrl": "..." } }
//   overrides/extends any entry.
// - Warns about files over Cloudflare Pages' 25 MiB per-file limit.
// Only add music you have the right to publish.
import { readdirSync, statSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, extname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DIR = join(ROOT, "Frontend", "assets", "music", "background");
const OUT = join(ROOT, "Frontend", "js", "background-playlist.js");
const PLAYABLE = new Set([".mp3", ".m4a", ".aac", ".ogg", ".oga", ".opus", ".wav"]);
const MAX_BYTES = 25 * 1024 * 1024;

if (!existsSync(DIR)) {
  console.error(`Folder not found: ${DIR}`);
  process.exit(1);
}

let credits = {};
const creditsFile = join(DIR, "credits.json");
if (existsSync(creditsFile)) credits = JSON.parse(readFileSync(creditsFile, "utf8"));

const tracks = [];
for (const name of readdirSync(DIR).sort((a, b) => a.localeCompare(b))) {
  const full = join(DIR, name);
  if (!statSync(full).isFile() || name === "credits.json" || name.startsWith(".") || /\.md$/i.test(name)) continue;
  const ext = extname(name).toLowerCase();
  if (!PLAYABLE.has(ext)) {
    console.warn(`skip (not a supported audio format): ${name}`);
    continue;
  }
  if (statSync(full).size > MAX_BYTES) {
    console.warn(`skip (over 25 MiB, Cloudflare Pages won't serve it): ${name}`);
    continue;
  }
  const title = basename(name, extname(name)).replace(/\s*\[[^\]]*\]\s*$/, "").trim();
  tracks.push(Object.assign({ src: "assets/music/background/" + encodeURIComponent(name), title }, credits[name] || {}));
}

if (!tracks.length) {
  console.error("No playable tracks found — leaving Frontend/js/background-playlist.js unchanged.");
  process.exit(1);
}

const header = `// Generated by scripts/build-music-playlist.mjs — edit the files in
// Frontend/assets/music/background/ (and its credits.json), then re-run it.
// Only add music you have the right to publish.
`;
writeFileSync(
  OUT,
  header +
    "window.PortfolioMusic = window.PortfolioMusic || {};\n" +
    "window.PortfolioMusic.playlist = " +
    JSON.stringify(tracks, null, 2) +
    ";\n"
);
console.log(`Wrote ${tracks.length} track(s) to ${OUT}`);
